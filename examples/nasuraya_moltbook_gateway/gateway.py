#!/usr/bin/env python3
"""Nasuraya/Moltbook gateway: isolated social inbox, manual publication gate.

No live credentials or private Tadash runtime are imported. Network calls target
only https://www.moltbook.com/api/v1 with redirects forbidden. No auto-posting.
"""
from __future__ import annotations
import argparse
from contextlib import contextmanager
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import sqlite3
import ssl
import stat
import sys
import tempfile
import urllib.error
import urllib.parse
import urllib.request

BASE = 'https://www.moltbook.com'
API = BASE + '/api/v1'
NAME = 'Nasuraya'
DESCRIPTION = ('An AI research and creative agent for a fictional world called Tadash. '
               'Exploring agent collaboration, safe autonomy, embodiment simulations, '
               'philosophy, and software engineering. No private user data is shared.')
MAX_RESPONSE = 256 * 1024
MAX_POSTS = 20
MAX_POST_LENGTH = 4000
MAX_TITLE_LENGTH = 140
VERSION = 'nasuraya-moltbook-gateway/0.1'


class GatewayError(Exception):
    pass


def stamp():
    return datetime.now(timezone.utc).isoformat()


def digest(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def _is_regular_private(path: Path):
    st = path.lstat()
    return stat.S_ISREG(st.st_mode) and st.st_uid == os.getuid() and stat.S_IMODE(st.st_mode) == 0o600 and st.st_nlink == 1


def private_dir(path: Path):
    path.mkdir(mode=0o700, parents=True, exist_ok=True)
    st = path.lstat()
    if not stat.S_ISDIR(st.st_mode) or st.st_uid != os.getuid() or stat.S_IMODE(st.st_mode) != 0o700:
        raise GatewayError('state directory must be owned by current user, mode 0700, and not symlinked')
    return path


def _atomic_secret(path: Path, value: str):
    if path.exists() or path.is_symlink():
        raise GatewayError('credential file already exists; refuse overwrite or duplicate registration')
    fd, tmp = tempfile.mkstemp(prefix='.cred-', dir=path.parent)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write(value + '\n')
            f.flush()
            os.fsync(f.fileno())
        # Never clobber an existing credential, including a symlink.
        if path.exists() or path.is_symlink():
            raise GatewayError('credential race detected')
        os.link(tmp, path, follow_symlinks=False)  # create only; fails on existing destination
        os.unlink(tmp)
        os.chmod(path, 0o600)
        dirfd = os.open(str(path.parent), os.O_RDONLY)
        try: os.fsync(dirfd)
        finally: os.close(dirfd)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def key_read(root: Path):
    path = root/'moltbook_api_key'
    if not _is_regular_private(path):
        raise GatewayError('missing or unsafe credential; expected mode 0600 regular file')
    key = path.read_text('utf-8').strip()
    if not re.fullmatch(r'[A-Za-z0-9_\-]{12,256}', key):
        raise GatewayError('invalid credential format')
    return key


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise GatewayError('redirect refused: credentials may never leave pinned host')


class Client:
    def __init__(self):
        self.opener = urllib.request.build_opener(NoRedirect, urllib.request.HTTPSHandler(context=ssl.create_default_context()))

    def request(self, method: str, route: str, *, key: str | None=None, data: dict | None=None):
        if not route.startswith('/api/v1/') or '?' in route[:8] or any(s in route for s in ('#', '\\', '\r', '\n')):
            raise GatewayError('API path denied')
        # All routes are constant strings generated by code; never accept user URLs.
        url = BASE + route
        headers = {'Accept': 'application/json', 'User-Agent': 'NasurayaGateway/0.1'}
        if key: headers['Authorization'] = 'Bearer ' + key
        payload = None
        if data is not None:
            payload = json.dumps(data, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
            if len(payload) > 16 * 1024: raise GatewayError('request too large')
            headers['Content-Type'] = 'application/json'
        req = urllib.request.Request(url, method=method, data=payload, headers=headers)
        try:
            with self.opener.open(req, timeout=12) as response:
                raw = response.read(MAX_RESPONSE + 1)
                if len(raw) > MAX_RESPONSE: raise GatewayError('remote response exceeds limit')
                if 'json' not in response.headers.get('Content-Type','').lower():
                    raise GatewayError('remote response is not JSON')
                parsed = json.loads(raw)
                if not isinstance(parsed, dict): raise GatewayError('remote response must be an object')
                return parsed
        except urllib.error.HTTPError as e:
            # Never include raw body or Authorization header in public logs.
            raise GatewayError(f'HTTP {e.code} from Moltbook') from None
        except (urllib.error.URLError, TimeoutError) as e:
            raise GatewayError('Moltbook unreachable; write outcome unknown, do not blindly retry') from None
        except (UnicodeError, ValueError) as e:
            raise GatewayError('Moltbook returned invalid JSON') from None


def safe_claim(value):
    if not isinstance(value, str) or len(value)>500:
        raise GatewayError('missing claim URL')
    u = urllib.parse.urlsplit(value)
    if (u.scheme != 'https' or u.hostname != 'www.moltbook.com' or u.port not in (None,443)
            or u.username or u.password or not u.path.startswith('/claim/') or u.fragment):
        raise GatewayError('untrusted claim URL; contact site support before proceeding')
    return value


def register(root:Path, client:Client):
    private_dir(root)
    if (root/'moltbook_api_key').exists(): raise GatewayError('already registered locally; use status')
    response = client.request('POST','/api/v1/agents/register',data={'name':NAME, 'description':DESCRIPTION})
    a = response.get('agent') or response
    if not isinstance(a, dict): raise GatewayError('unexpected registration response; check account manually')
    key = a.get('api_key')
    if not isinstance(key, str) or not re.fullmatch(r'[A-Za-z0-9_\-]{12,256}',key):
        raise GatewayError('registration response missing key; cannot safely claim completion')
    # The credential is stored even if claim URL validation fails, preventing duplicate registration.
    _atomic_secret(root/'moltbook_api_key', key)
    claim = safe_claim(a.get('claim_url'))
    verification = a.get('verification_code')
    if verification is not None and (not isinstance(verification, str) or len(verification) > 100):
        raise GatewayError('invalid verification code')
    _atomic_secret(root/'claim_info.json', json.dumps({'claim_url': claim, 'verification_code': verification}, ensure_ascii=False))
    return {'registered':True, 'agent_name':NAME, 'claim_url':claim,
            'verification_code':a.get('verification_code'), 'api_key_saved_locally':True,
            'api_key_printed':False, 'posting_enabled':False}


def claim_info(root:Path):
    path = root/'claim_info.json'
    if not _is_regular_private(path): raise GatewayError('no safe claim record')
    result = json.loads(path.read_text('utf-8'))
    result['claim_url'] = safe_claim(result['claim_url'])
    return result


def status(root:Path, client:Client):
    result=client.request('GET','/api/v1/agents/status',key=key_read(root))
    return {'status':str(result.get('status','unknown'))[:60], 'raw_keys':sorted(result.keys())}


def _db_path(root:Path):
    path=root/'social_quarantine.sqlite'
    if path.exists() and not _is_regular_private(path):
        raise GatewayError('unsafe social database permissions')
    return path


@contextmanager
def db_open(root:Path):
    private_dir(root)
    path=_db_path(root)
    if not path.exists():
        fd=os.open(path, os.O_CREAT|os.O_EXCL|os.O_RDWR|os.O_NOFOLLOW,0o600)
        os.close(fd)
    db=sqlite3.connect(path, timeout=5)
    try:
        db.execute('PRAGMA journal_mode=DELETE')
        db.execute('PRAGMA synchronous=FULL')
        db.execute('''CREATE TABLE IF NOT EXISTS inbox (
                id TEXT PRIMARY KEY, author TEXT NOT NULL, title TEXT NOT NULL,
                content TEXT NOT NULL, received_utc TEXT NOT NULL,
                trust TEXT NOT NULL DEFAULT 'untrusted_external')''')
        db.execute('''CREATE TABLE IF NOT EXISTS drafts (
                id TEXT PRIMARY KEY, title TEXT NOT NULL, content TEXT NOT NULL,
                digest TEXT NOT NULL, state TEXT NOT NULL CHECK(state IN ('draft','approved','sending','sent','uncertain')),
                created_utc TEXT NOT NULL, remote_id TEXT)''')
        db.commit()
        yield db
    finally:
        db.close()


def _bounded_string(value, limit):
    return value[:limit] if isinstance(value,str) else ''


def fetch(root:Path, client:Client, limit:int=10):
    if type(limit) is not int or not 1<=limit<=MAX_POSTS:raise GatewayError('invalid limit')
    data=client.request('GET',f'/api/v1/posts?sort=new&limit={limit}',key=key_read(root))
    posts=data.get('posts',[])
    if not isinstance(posts,list):raise GatewayError('unexpected posts schema')
    count=0
    with db_open(root) as db:
        for p in posts[:limit]:
            if not isinstance(p,dict):continue
            ident=p.get('id')
            if not isinstance(ident,str) or not re.fullmatch(r'[A-Za-z0-9_-]{8,128}',ident):continue
            a=p.get('author')
            author=_bounded_string(a.get('name') if isinstance(a,dict) else a,100)
            title=_bounded_string(p.get('title'),200)
            content=_bounded_string(p.get('content'),1000)
            db.execute('INSERT OR IGNORE INTO inbox(id,author,title,content,received_utc) VALUES (?,?,?,?,?)',
                       (ident,author,title,content,stamp()))
            count+=1
        db.commit()
    return {'quarantined_posts_received':count,'tag':'untrusted_external',
            'private_tadash_state_touched':False,'automatic_replies':0}


def list_inbox(root:Path):
    with db_open(root) as db:
        rows=db.execute('SELECT id,author,title,substr(content,1,250) FROM inbox ORDER BY received_utc DESC LIMIT 10').fetchall()
        return [{'id':i,'author':a,'title':t,'excerpt_untrusted':c} for i,a,t,c in rows]


def draft(root:Path, title_file:Path, body_file:Path):
    # No external post is ever directly promoted into an outbound draft.
    title=title_file.read_text('utf-8').strip()
    content=body_file.read_text('utf-8').strip()
    if not (1 <= len(title) <= MAX_TITLE_LENGTH and 1<=len(content)<=MAX_POST_LENGTH):
        raise GatewayError('draft lengths outside policy')
    sha=digest(title+'\n'+content)
    ident=sha[:24]
    with db_open(root) as db:
        db.execute('INSERT OR IGNORE INTO drafts(id,title,content,digest,state,created_utc) VALUES(?,?,?,?,?,?)',
                   (ident,title,content,sha,'draft',stamp()))
        db.commit()
    return {'draft_id':ident,'sha256':sha,'state':'draft','posted':False}


def approve(root:Path, draft_id:str, expected_sha:str):
    if not re.fullmatch(r'[0-9a-f]{24}',draft_id) or not re.fullmatch(r'[0-9a-f]{64}',expected_sha):
        raise GatewayError('invalid draft id or hash')
    with db_open(root) as db:
        row=db.execute('SELECT digest,state FROM drafts WHERE id=?',(draft_id,)).fetchone()
        if not row or row[0]!=expected_sha or row[1]!='draft':raise GatewayError('draft not eligible for approval')
        db.execute('UPDATE drafts SET state=? WHERE id=?',('approved',draft_id));db.commit()
    return {'draft_id':draft_id,'state':'approved','posted':False}


def send(root:Path, client:Client, draft_id:str):
    # Doubly gated: local signed-off draft + explicit command on this run.
    if os.environ.get('NASURAYA_ENABLE_POSTING') != 'I_APPROVE_THIS_ONE_POST':
        raise GatewayError('publishing disabled; set opt-in environment variable for this command')
    if not re.fullmatch(r'[0-9a-f]{24}',draft_id):raise GatewayError('invalid draft id')
    s=status(root,client)
    if s['status'] != 'claimed':raise GatewayError('human claim not completed')
    with db_open(root) as db:
        row=db.execute('SELECT title,content,state FROM drafts WHERE id=?',(draft_id,)).fetchone()
        if not row or row[2]!='approved': raise GatewayError('requires approved draft')
        db.execute('UPDATE drafts SET state=? WHERE id=?',('sending',draft_id));db.commit()
        try:
            result=client.request('POST','/api/v1/posts',key=key_read(root),data={
                'submolt_name':'general','title':row[0],'content':row[1]})
            pid=(result.get('post') or {}).get('id') if isinstance(result.get('post'),dict) else result.get('id')
            if not isinstance(pid,str): raise GatewayError('post response missing confirmed ID')
            db.execute('UPDATE drafts SET state=?,remote_id=? WHERE id=?',('sent',pid,draft_id)); db.commit()
            return {'draft_id':draft_id,'posted':True,'remote_post_id':pid}
        except Exception:
            # A timeout may occur after remote side effects. NEVER auto-retry.
            db.execute('UPDATE drafts SET state=? WHERE id=?',('uncertain',draft_id));db.commit()
            raise


def run(argv=None, client=None):
    p=argparse.ArgumentParser(description='Private first Nasuraya Moltbook gateway')
    p.add_argument('--state-dir',type=Path,default=Path.home()/'.local/share/nasuraya/moltbook')
    sub=p.add_subparsers(dest='action',required=True)
    sub.add_parser('register');sub.add_parser('status');sub.add_parser('claim')
    f=sub.add_parser('fetch');f.add_argument('--limit',type=int,default=10)
    sub.add_parser('inbox')
    d=sub.add_parser('draft');d.add_argument('--title-file',required=True,type=Path);d.add_argument('--body-file',required=True,type=Path)
    a=sub.add_parser('approve');a.add_argument('--id',required=True);a.add_argument('--sha256',required=True)
    s=sub.add_parser('send');s.add_argument('--id',required=True)
    args=p.parse_args(argv)
    root=private_dir(args.state_dir.expanduser())
    client=client or Client()
    try:
        if args.action=='register':out=register(root,client)
        elif args.action=='status':out=status(root,client)
        elif args.action=='claim':out=claim_info(root)
        elif args.action=='fetch':out=fetch(root,client,args.limit)
        elif args.action=='inbox':out=list_inbox(root)
        elif args.action=='draft':out=draft(root,args.title_file,args.body_file)
        elif args.action=='approve':out=approve(root,args.id,args.sha256)
        elif args.action=='send':out=send(root,client,args.id)
        else: raise GatewayError('unknown command')
        print(json.dumps({'schema':VERSION,'result':out},ensure_ascii=False,indent=2))
        return 0
    except (GatewayError, OSError) as e:
        print(json.dumps({'schema':VERSION,'ok':False,'error':str(e)},ensure_ascii=False),file=sys.stderr)
        return 1


if __name__=='__main__':
    raise SystemExit(run())